--   8 enums, 41 tables, 47 constraints, 81 indexes, 43 functions,
--   9 views+matviews, 12 triggers
--
-- Deliberately EXCLUDED:
--   * objects owned by extensions (pg_trgm etc.) - 31 functions. pg_dump
--     omits these too; they come back via CREATE EXTENSION.
--   * RLS and policies - already captured in rls_policies.sql
--   NOTE: table and function GRANTs ARE included (ord 8). pg_get_functiondef()
--   omits them, so they must be emitted separately or they are silently lost.
--   * table DATA - schema only
--
-- CAVEAT: reconstructed from catalog, not produced by pg_dump. Ordering is
-- by object class, not dependency, so it is a faithful RECORD rather than a
-- guaranteed clean replay. Test against a scratch database before relying on
-- it to rebuild.
